export function enrichAagamItem(item: AagamItem): AagamItem {
  const hasEllipsis = item.content.includes('...') || item.content.includes('॥...');
  const isShort = item.content.trim().split('\n').length < 6;
  const isSpecialShort = item.id === 'stuti_8' || item.id === 'stuti_9' || item.id === 'stuti_10';

  if ((hasEllipsis || isShort) && !isSpecialShort) {
    const name = extractDeityName(item.title);
    const meta = DEITY_META[name] || {};
    let content = item.content;

    if (item.category === 'Pujan') {
      if (item.id === 'pujan_10') {
        content = `॥ चौबीस तीर्थंकर अर्घ्यावली ॥\n(प्रथम ऋषभदेव से २४वें महावीर भगवान तक सभी जिनेन्द्रों की अर्घ्यावली)\n\n` + 
          names24.map((n, idx) => `${idx + 1}. श्री ${n} भगवान अर्घ्य:\nॐ ह्रीं श्री ${n === 'वर्धमान महावीर' ? 'वर्धमानमहावीर' : n}जिनेन्द्राय संसारताप-विनाशनाय अर्घ्यं निर्वपामीति स्वाहा।`).join('\n\n');
      } else {
        content = generatePujan(name, meta);
      }
    } else if (item.category === 'Chalisa') {
      content = generateChalisa(name, meta);
    } else if (item.category === 'Aarti') {
      content = generateAarti(name, meta);
    } else if (item.category === 'Stuti') {
      content = generateStuti(name, meta);
    } else if (item.category === 'Vidhan') {
      content = generateVidhan(name, meta);
    } else if (item.category === 'Bhajan') {
      content = generateBhajan(name, meta);
    }
    
    return {
      ...item,
      content
    };
  }
  
  return item;
}

const CATEGORIES: ('Pujan' | 'Stuti' | 'Vidhan' | 'Chalisa' | 'Bhajan' | 'Aarti')[] = ['Pujan', 'Stuti', 'Vidhan', 'Chalisa', 'Bhajan', 'Aarti'];

const expandedAagams: AagamItem[] = [...baseAagamsData];

CATEGORIES.forEach(cat => {
  const existing = baseAagamsData.filter(item => item.category === cat);
  const countNeeded = 60 - existing.length;
  
  if (countNeeded > 0) {
    for (let i = 0; i < countNeeded; i++) {
      const nameIndex = (i + existing.length) % extraTirthankaras.length;
      const name = extraTirthankaras[nameIndex];
      const id = `${cat.toLowerCase()}_gen_${i + existing.length + 1}`;
      
      let title = "";
      let content = "";
      const meta = DEITY_META[name] || {};
      
      if (cat === 'Pujan') {
        title = `श्री ${name} पूजा (Shree ${name} Puja - पूर्ण देव पूजा)`;
        content = generatePujan(name, meta);
      } else if (cat === 'Stuti') {
        title = `श्री ${name} स्तुति पाठ (Shree ${name} Stuti - वैराग्य स्तोत्र)`;
        content = generateStuti(name, meta);
      } else if (cat === 'Vidhan') {
        title = `श्री ${name} महामंडल विधान (Shree ${name} Mahamandal Vidhan)`;
        content = generateVidhan(name, meta);
      } else if (cat === 'Chalisa') {
        title = `श्री ${name} चालीसा (Shree ${name} Chalisa - संकट मोचन)`;
        content = generateChalisa(name, meta);
      } else if (cat === 'Bhajan') {
        title = `श्री ${name} भक्ति भजन (Shree ${name} Bhajan - मधुर रस)`;
        content = generateBhajan(name, meta);
      } else if (cat === 'Aarti') {
        title = `श्री ${name} आरती (Shree ${name} Aarti - मंगल दीप)`;
        content = generateAarti(name, meta);
      }
      
      expandedAagams.push({ id, category: cat, title, content });
    }
  }
});

// Post-process the base and expanded items to make sure absolutely everything is fully detailed
export const aagamsData = expandedAagams.map(enrichAagamItem);
