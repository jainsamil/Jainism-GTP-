function generateChalisa(name: string, meta: DeityMeta): string {
  const lineParents = meta.parentMale ? `श्री ${meta.parentMale} के राजदुलारे, माता ${meta.parentFemale} के नयनतारे।` : "तीन लोक के नाथ कहावो, भव्य जनों के पार लगावो।";
  const lineBirth = meta.birthplace ? `${meta.birthplace} में जनम सुहाया, सुर-नर सुरपति मंगल गाया।` : "शांत वीतराग रूप तुम्हारा, संकट संकट सकल विडारा।";
  const extra = meta.extraVerse ? meta.extraVerse : "";

  return `॥ श्री ${name} चालीसा ॥
(परम पावन संकट निवारक पाठ)

[दोहा]
श्री गुरु पद रज शीश धर, सुमरी ${name} जिनेश।
चालीसा वर्णन करूँ, मिटे सकल क्लेश॥

[चौपाई]
जय ${name} देव सुखकारी, हरहु सकल दुःख व्याधि हमारी।
वीतराग मुद्रा अति प्यारी, मोह महातम भंजनहारी॥ १ ॥

${lineParents}
${lineBirth}॥ २ ॥

शांत दिगंबर रूप प्रवीणा, राग द्वेष से विरहित कीना।
ज्ञान भानु प्रगटायो प्रदीपा, आतम तत्व मिला सुख सीपा॥ ३ ॥

दया धरम की ज्योति जगाई, हिंसा और कुबुद्धि नशाई।
स्याद्वाद मारग सुखदाई, प्राणी मात्र को शांति सिखाई॥ ४ ॥

समवशरण प्रभु अति मनभावन, दिव्यध्वनि बरसावे पावन।
जो प्राणी शरणे में आवे, भव-भव के बंध सब कट जावे॥ ५ ॥

${extra ? extra + "॥ ६ ॥\n" : ""}तुम्हारा सुमिरन करे जो कोई, जनम जनम दुःख संकट खोई।
पुत्र पौत्र सुख सम्पति बाढ़े, दुःख दारिद्र कषाय निवारे॥ ७ ॥

तुम हो रक्षक तुम ही दाता, तीन जगत के तुम हो त्राता।
हम आये चरनन में शरण, राखो लाज हरो सब मरण॥ ८ ॥

[दोहा]
चालीसा चालीस दिन, पाठ करें मन लाय।
प्रभु ${name} की कृपा से, सकल विघ्न मिट जाय॥
वीतराग पद प्रगट हो, आतम सुख प्रगटाय॥`;
}

