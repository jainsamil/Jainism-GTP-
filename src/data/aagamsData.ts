function extractDeityName(title: string): string {
  for (const name of extraTirthankaras) {
    if (title.includes(name)) return name;
  }
  if (title.includes("महावीर")) return "वर्धमान महावीर";
  if (title.includes("आदिनाथ")) return "आदिनाथ";
  if (title.includes("पार्श्वनाथ") || title.includes("पारसनाथ")) return "पार्श्वनाथ";
  if (title.includes("बाहुबली")) return "बाहुबली";
  if (title.includes("सरस्वती") || title.includes("जिनवाणी")) return "जिनवाणी माता";
  if (title.includes("पंचपरमेष्ठी")) return "पंचपरमेष्ठी देव";
  if (title.includes("नवदेवता")) return "नवदेवता देव";
  if (title.includes("सोलहकारण")) return "सोलहकारण भावना";
  if (title.includes("दशलक्षण")) return "दशलक्षण धर्म";
  if (title.includes("सिद्धचक्र")) return "सिद्धचक्र भगवान";
  
  const match = title.match(/श्री ([^ (]+)/);
  if (match) return match[1];
  return "जिनेन्द्र देव";
}

